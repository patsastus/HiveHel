int	ft_isalpha(int c)
{
	int				is_alpha;

	is_alpha = 1;
	if (!((c >= 'A' && c <= 'Z') || (c >= 'a' && c <= 'z')))
		is_alpha = 0;
	return (is_alpha);
}
